import type { ToolDefinition } from "../../core/types.js";
import type { GitManager } from "./manager.js";
import {
  GitAddInputSchema,
  GitBranchInputSchema,
  GitCheckoutInputSchema,
  GitCloneInputSchema,
  GitCommitInputSchema,
  GitDiffInputSchema,
  GitInitInputSchema,
  GitLogInputSchema,
  GitMergeInputSchema,
  GitPullInputSchema,
  GitPushInputSchema,
  GitStatusInputSchema,
  GitTagInputSchema,
} from "./types.js";

export function createGitTools(gitManager: GitManager): ToolDefinition[] {
  return [
    {
      name: "git.status",
      description: "Checks working tree and branch status of the Git repository",
      category: "git",
      defaultPermission: "AUTO",
      inputSchema: GitStatusInputSchema,
      execute: (input, context) => gitManager.status(GitStatusInputSchema.parse(input), context),
    },
    {
      name: "git.diff",
      description: "Shows unstaged or staged diff in the Git repository",
      category: "git",
      defaultPermission: "AUTO",
      inputSchema: GitDiffInputSchema,
      execute: (input, context) => gitManager.diff(GitDiffInputSchema.parse(input), context),
    },
    {
      name: "git.log",
      description: "Lists recent commit history in the Git repository",
      category: "git",
      defaultPermission: "AUTO",
      inputSchema: GitLogInputSchema,
      execute: (input, context) => gitManager.log(GitLogInputSchema.parse(input), context),
    },
    {
      name: "git.branch",
      description: "Lists, creates or safely deletes (-d) branches in the Git repository",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitBranchInputSchema,
      execute: (input, context) => gitManager.branch(GitBranchInputSchema.parse(input), context),
    },
    {
      name: "git.tag",
      description: "Lists, creates or deletes tags in the Git repository",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitTagInputSchema,
      execute: (input, context) => gitManager.tag(GitTagInputSchema.parse(input), context),
    },
    {
      name: "git.init",
      description: "Initializes a new Git repository inside the authorized workspace",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitInitInputSchema,
      execute: (input, context) => gitManager.init(GitInitInputSchema.parse(input), context),
    },
    {
      name: "git.clone",
      description: "Clones a remote Git repository into a directory inside the workspace",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitCloneInputSchema,
      execute: (input, context) => gitManager.clone(GitCloneInputSchema.parse(input), context),
    },
    {
      name: "git.checkout",
      description: "Switches branches or creates and checks out a new branch",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitCheckoutInputSchema,
      execute: (input, context) =>
        gitManager.checkout(GitCheckoutInputSchema.parse(input), context),
    },
    {
      name: "git.add",
      description: "Stages validated workspace file paths into the Git index",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitAddInputSchema,
      execute: (input, context) => gitManager.add(GitAddInputSchema.parse(input), context),
    },
    {
      name: "git.commit",
      description: "Creates a Git commit after verifying no sensitive files are staged",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitCommitInputSchema,
      execute: (input, context) => gitManager.commit(GitCommitInputSchema.parse(input), context),
    },
    {
      name: "git.pull",
      description: "Pulls changes from a remote repository (fast-forward only by default)",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitPullInputSchema,
      execute: (input, context) => gitManager.pull(GitPullInputSchema.parse(input), context),
    },
    {
      name: "git.push",
      description: "Publishes commits to a remote repository (always requires human approval)",
      category: "git",
      defaultPermission: "HUMAN_APPROVAL",
      inputSchema: GitPushInputSchema,
      execute: (input, context) => gitManager.push(GitPushInputSchema.parse(input), context),
    },
    {
      name: "git.merge",
      description: "Merges a branch into the current branch",
      category: "git",
      defaultPermission: "CONDITIONAL",
      inputSchema: GitMergeInputSchema,
      execute: (input, context) => gitManager.merge(GitMergeInputSchema.parse(input), context),
    },
  ];
}
